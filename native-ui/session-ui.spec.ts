import { expect, test } from '@playwright/test'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

test('local UI session flow uses responsive Ant Design navigation', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '登录本地控制台' })).toBeVisible()
  await page.getByLabel('本地 UI 登录口令').fill('wrong-password')
  await page.getByRole('button', { name: '登录' }).click()
  await expect(page.getByRole('alert')).toContainText('本地 UI 口令不正确')
  await page.getByLabel('本地 UI 登录口令').fill('smoke-password')
  await page.getByRole('button', { name: '登录' }).click()
  await expect(page.getByRole('heading', { name: '运行概览' })).toBeVisible()
  const nav = page.getByRole('menu')
  await expect(nav.getByRole('menuitem', { name: '插件目录' })).toBeVisible()
  await nav.getByRole('menuitem', { name: '插件目录' }).click()
  await expect(page.getByRole('heading', { name: '已发现插件' })).toBeVisible()
  await expect(page.getByRole('table')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: join(tmpdir(), 'plugmesh-local-desktop.png'), fullPage: true })
  await page.getByRole('button', { name: '退出登录' }).click()
  await expect(page.getByRole('heading', { name: '登录本地控制台' })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByLabel('本地 UI 登录口令').fill('smoke-password')
  await page.getByRole('button', { name: '登录' }).click()
  const mobileMenu = page.getByRole('menu')
  await expect(mobileMenu).toBeHidden()
  await page.getByRole('button', { name: '切换导航菜单' }).click()
  await expect(mobileMenu).toBeVisible()
  await mobileMenu.getByRole('menuitem', { name: '端口映射' }).click()
  await expect(page.getByRole('heading', { name: '跨服务器 TCP 映射' })).toBeVisible()
  await expect(mobileMenu).toBeHidden()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: join(tmpdir(), 'plugmesh-local-mobile.png'), fullPage: true })
})

test('local UI plugin operations remain available from the Plugins screen', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('本地 UI 登录口令').fill('smoke-password')
  await page.getByRole('button', { name: '登录' }).click()
  await page.getByRole('menuitem', { name: '插件目录' }).click()
  const row = page.locator('.ant-table-row').filter({ hasText: 'Sample Plugin' })
  await expect(row).toContainText('已发现')
  await row.getByRole('button', { name: '加载' }).click()
  await expect(row).toContainText('已加载')
  await row.getByRole('button', { name: '启用' }).click()
  await expect(row).toContainText('已启用')
  await row.getByRole('button', { name: '检查' }).click()
  await expect(page.getByRole('alert')).toContainText('健康检查通过')
  await row.getByRole('button', { name: '停用' }).click()
  await expect(row).toContainText('已停用')
  await row.getByRole('button', { name: '卸载' }).click()
  await expect(row).toContainText('已卸载')
})

test('local UI mappings screen restricts targets to online servers and verifies passwords in a modal', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('本地 UI 登录口令').fill('smoke-password')
  await page.getByRole('button', { name: '登录' }).click()
  await page.getByRole('menuitem', { name: '端口映射' }).click()
  await page.getByRole('button', { name: '刷新目标服务器' }).click()
  const targetRow = page.locator('.ant-table-row').filter({ hasText: 'target-server' })
  await expect(targetRow).toContainText('需要授权')
  await targetRow.getByRole('button', { name: '验证' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('目标服务器口令（仅首次信任时需要）').fill('smoke-password')
  await dialog.getByRole('button', { name: '验证口令' }).click()
  await expect(targetRow).toContainText('已授权')
  await expect(dialog).toBeHidden()
  await page.getByLabel('映射名称').fill('ssh-local')
  await page.getByLabel('本地监听端口').fill('2222')
  await page.getByLabel('目标主机').fill('127.0.0.1')
  await page.getByLabel('目标端口').fill('22')
  await page.getByRole('button', { name: '添加映射' }).click()
  await expect(page.getByRole('row', { name: /ssh-local/ })).toContainText('127.0.0.1:2222')
})

