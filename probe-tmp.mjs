import { chromium } from '@playwright/test'
const token = 'e2e-session-token'
const browser = await chromium.launch()
const context = await browser.newContext()
await context.addCookies([{ name: 'plugmesh_session', value: token, url: 'http://127.0.0.1:18889' }])
const page = await context.newPage()
page.on('console', (m) => console.log('[console]', m.type(), m.text()))
page.on('pageerror', (e) => console.log('[pageerror]', e.message))
await page.goto('http://127.0.0.1:18889/')
await page.getByRole('button', { name: '插件实例', exact: true }).click()
await page.getByRole('button', { name: '公开域名', exact: true }).click()
await page.waitForTimeout(500)
await page.getByRole('button', { name: '插件实例', exact: true }).click()
const row = page.getByRole('row', { name: /Sample Plugin.*console-mvi4ck8x/ })
console.log('rows', await row.count())
await row.getByRole('button', { name: '查看 Sample Plugin 详情' }).click()
await page.waitForTimeout(2000)
console.log('dialogs', await page.getByRole('dialog').count())
console.log((await page.locator('.modal-backdrop').count()))
await browser.close()
